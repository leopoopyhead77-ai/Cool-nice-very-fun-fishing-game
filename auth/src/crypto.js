const MASK64 = (1n << 64n) - 1n;
const rotr64 = (x, n) => ((x >> n) | (x << (64n - n))) & MASK64;

/**
 * SHA-512 (FIPS 180-4). Returns 64 bytes.
 *
 * BigInt rather than split 32-bit words: almost nothing issues SHA-512 TOTP
 * secrets, so clarity beats speed here.
 */
export function sha512(msg) {
  const total = Math.ceil((msg.length + 17) / 128) * 128;
  const buf = new Uint8Array(total);
  buf.set(msg);
  buf[msg.length] = 0x80;
  const dv = new DataView(buf.buffer);
  dv.setUint32(total - 4, (msg.length * 8) >>> 0);
  dv.setUint32(total - 8, Math.floor((msg.length * 8) / 0x100000000));

  const h = [
    "6a09e667f3bcc908", "bb67ae8584caa73b", "3c6ef372fe94f82b", "a54ff53a5f1d36f1",
    "510e527fade682d1", "9b05688c2b3e6c1f", "1f83d9abfb41bd6b", "5be0cd19137e2179",
  ].map((s) => BigInt("0x" + s));
  const w = new Array(80);

  for (let i = 0; i < total; i += 128) {
    for (let t = 0; t < 16; t++) {
      w[t] = (BigInt(dv.getUint32(i + t * 8)) << 32n) | BigInt(dv.getUint32(i + t * 8 + 4));
    }
    for (let t = 16; t < 80; t++) {
      const x = w[t - 15], y = w[t - 2];
      const s0 = rotr64(x, 1n) ^ rotr64(x, 8n) ^ (x >> 7n);
      const s1 = rotr64(y, 19n) ^ rotr64(y, 61n) ^ (y >> 6n);
      w[t] = (w[t - 16] + s0 + w[t - 7] + s1) & MASK64;
    }
    let [a, b, c, d, e, f, g, hh] = h;
    for (let t = 0; t < 80; t++) {
      const S1 = rotr64(e, 14n) ^ rotr64(e, 18n) ^ rotr64(e, 41n);
      const ch = (e & f) ^ (~e & MASK64 & g);
      const t1 = (hh + S1 + ch + K512[t] + w[t]) & MASK64;
      const S0 = rotr64(a, 28n) ^ rotr64(a, 34n) ^ rotr64(a, 39n);
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const t2 = (S0 + maj) & MASK64;
      hh = g; g = f; f = e; e = (d + t1) & MASK64; d = c; c = b; b = a; a = (t1 + t2) & MASK64;
    }
    const add = [a, b, c, d, e, f, g, hh];
    for (let t = 0; t < 8; t++) h[t] = (h[t] + add[t]) & MASK64;
  }

  const out = new Uint8Array(64);
  for (let i = 0; i < 8; i++) {
    let v = h[i];
    for (let j = 7; j >= 0; j--) { out[i * 8 + j] = Number(v & 0xffn); v >>= 8n; }
  }
  return out;
}

export const HASHES = {
  SHA1: { fn: sha1, block: 64 },
  SHA256: { fn: sha256, block: 64 },
  SHA512: { fn: sha512, block: 128 },
};

/** HMAC (RFC 2104) over any of the hashes above. */
export function hmac(algorithm, key, message) {
  const spec = HASHES[algorithm];
  if (!spec) throw new Error("unsupported algorithm: " + algorithm);
  const { fn, block } = spec;

  let k = key.length > block ? fn(key) : key;
  const padded = new Uint8Array(block);
  padded.set(k);

  const inner = new Uint8Array(block + message.length);
  const outer = new Uint8Array(block + fn(new Uint8Array(0)).length);
  for (let i = 0; i < block; i++) {
    inner[i] = padded[i] ^ 0x36;
    outer[i] = padded[i] ^ 0x5c;
  }
  inner.set(message, block);
  outer.set(fn(inner), block);
  return fn(outer);
}
